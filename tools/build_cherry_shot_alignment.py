"""Register the unchanged eye/face region to idle in the two forward diagonals.
Only produces horizontal anchor metadata; never rewrites sprite PNGs.
Requires Pillow, numpy and scipy. Run after build_cherry_geometry.py.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy.signal import correlate2d

ROOT=Path(__file__).resolve().parents[1]
GEOMETRY=json.loads((ROOT/'src/cherrift_cherry_geometry.js').read_text().split(' = ',1)[1].rstrip(';\n'))
# Eye strips in idle frame zero, right-facing diagonal. Avoid hair, hands,
# weapons and the mouth: all of these legitimately move while firing.
REFERENCES={'cherry_default':('base_cherry',(75,76,127,118)),
 'archer_cherry':('archer_cherry',(88,90,135,128)),
 'ninja_cherry':('ninja_cherry',(85,78,133,120))}

def normalized(frame,g):
    top,bottom,foot=g
    scale=156/(bottom-top)
    # Resample into the exact coordinate system of the runtime draw call.
    rgba=frame.transform((320,224),Image.Transform.AFFINE,
      (1/scale,0,foot-160/scale,0,1/scale,bottom-200/scale),Image.Resampling.BICUBIC)
    a=np.asarray(rgba,dtype=float)/255
    rgb=a[:,:,:3]*a[:,:,3:4]+.6*(1-a[:,:,3:4])
    return rgb.mean(axis=2),scale

def main():
    result={};report=[]
    for skin,(folder,eye_box) in REFERENCES.items():
        states=GEOMETRY[skin];result[skin]={}
        for direction in ['down_right','down_left']:
            idle=Image.open(ROOT/f'assets/player/cherry_skins/{folder}/sheets192/{folder}_idle_{direction}.png').convert('RGBA')
            g=states['idle'][direction][0];ref,scale=normalized(idle.crop((0,0,192,192)),g)
            x0,y0,x1,y1=eye_box
            if direction=='down_left':x0,x1=193-x1,193-x0
            left=round(160+(x0-g[2])*scale);right=round(160+(x1-g[2])*scale)
            top=round(200+(y0-g[1])*scale);bottom=round(200+(y1-g[1])*scale)
            template=ref[top:bottom,left:right];h,w=template.shape
            centered=template-template.mean();energy=np.sum(centered**2)
            assert energy>0
            for state in ['idle','attack','attack_ranged']:
                if state not in states:continue
                sheet=Image.open(ROOT/f'assets/player/cherry_skins/{folder}/sheets192/{folder}_{state}_{direction}.png').convert('RGBA')
                anchors=[];scores=[]
                for i,geometry in enumerate(states[state][direction]):
                    target,s=normalized(sheet.crop((i*192,0,(i+1)*192,192)),geometry)
                    lx=max(0,left-42);ly=max(0,top-28)
                    region=target[ly:min(224,bottom+28),lx:min(320,right+42)]
                    sums=correlate2d(region,np.ones((h,w)),mode='valid')
                    square=correlate2d(region**2,np.ones((h,w)),mode='valid')
                    variance=np.maximum(1e-12,square-sums**2/(h*w))
                    score=correlate2d(region,centered,mode='valid')/np.sqrt(variance*energy)
                    yy,xx=np.unravel_index(np.argmax(score),score.shape)
                    dx=lx+int(xx)-left
                    anchors.append(round(geometry[2]+dx/s,4));scores.append(round(float(score[yy,xx]),3))
                result[skin].setdefault(state,{})[direction]=anchors
                report.append([skin,state,direction,min(scores),anchors])
    (ROOT/'src/cherrift_cherry_shot_alignment.js').write_text(
      '/* Generated by tools/build_cherry_shot_alignment.py; original sprite pixels are unchanged. */\nwindow.CHERRIFT_CHERRY_SHOT_ALIGNMENT = '+json.dumps(result,separators=(',',':'))+';\n')
    for row in report:print(*row)

if __name__=='__main__':main()
