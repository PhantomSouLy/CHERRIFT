"""Measure the shipped RGBA strips; keep source artwork untouched.
Run after replacing animation strips. Requires Pillow and numpy.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]

def build():
    data = {}
    for folder, skin_id in [('base_cherry', 'cherry_default'), ('archer_cherry', 'archer_cherry'), ('ninja_cherry', 'ninja_cherry')]:
        states = {}
        for path in sorted((ROOT / 'assets/player/cherry_skins' / folder / 'sheets192').glob('*.png')):
            suffix = path.stem[len(folder) + 1:]
            # Longest direction first; state names also contain underscores.
            direction = next(d for d in ['down_right', 'down_left', 'up_right', 'up_left', 'right', 'left', 'down', 'up'] if suffix.endswith('_' + d))
            state = suffix[:-len(direction)-1]
            im = Image.open(path).convert('RGBA')
            frames = []
            for i in range(im.width // 192):
                a = np.array(im.crop((i*192, 0, (i+1)*192, 192)).getchannel('A'))
                yy, xx = np.where(a >= 160)
                assert len(xx), (path, i, 'empty')
                top, bottom = int(yy.min()), int(yy.max())+1
                # The soles, rather than the hair/bow silhouette, anchor x.
                fy, fx = np.where(a[max(top, bottom-12):bottom] >= 160)
                foot_x = float(np.median(fx)) + .5
                frames.append([top, bottom, foot_x])
            states.setdefault(state, {})[direction] = frames
        data[skin_id] = states
    output = '/* Generated by tools/build_cherry_geometry.py from shipped sprite alpha. */\nwindow.CHERRIFT_CHERRY_GEOMETRY = ' + json.dumps(data, separators=(',', ':')) + ';\n'
    (ROOT / 'src/cherrift_cherry_geometry.js').write_text(output)

if __name__ == '__main__':
    build()
